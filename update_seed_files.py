    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find where the dictionary closes
    target = "\n}"
    if target in content:
        # Before replacing, make sure we have a comma
        content = content.replace('\n}', ',\n' + SEED_DATA_EXTRA[peetha] + '\n}')
